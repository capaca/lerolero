import puppeteer from 'puppeteer-core'
const BASE = 'http://localhost:4181/lerolero/'
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', defaultViewport: { width: 400, height: 900 } })
const ok = (c, m) => console.log(c ? '✓' : '✗', m)
const page = await browser.newPage()
page.on('pageerror', (e) => console.log('ERRO:', String(e)))
const click = (l) => page.evaluate((l) => { const e = [...document.querySelectorAll('a,button')].find((e) => e.textContent.trim().startsWith(l)); if (!e) throw new Error('sem ' + l); e.click() }, l)
const text = () => page.evaluate(() => document.body.innerText)
// páginas públicas, sem conta
await page.goto(BASE + 'teste'); await new Promise((r) => setTimeout(r, 800))
ok((await page.evaluate(() => location.pathname)).endsWith('/teste') && (await text()).includes('Como testar o Lero-lero'), 'guia abre sem conta')
await page.goto(BASE + 'teste/roteiro'); await new Promise((r) => setTimeout(r, 800))
ok((await text()).includes('Roteiro de aceite') && (await page.$$('tbody tr')).length >= 14, 'roteiro abre sem conta, com os 14 passos')
// conta e comentário
await page.goto(BASE); await page.waitForFunction(() => location.pathname.endsWith('/bem-vindo'))
ok((await text()).includes('como testar'), 'boas-vindas tem o link "como testar"')
await click('Criar minha conta'); await page.waitForSelector('#nome'); await page.type('#nome', 'Testadora'); await click('Continuar')
await page.waitForSelector('#pin'); await page.type('#pin', '111111'); await page.type('#pin2', '111111'); await click('Criar conta')
await page.waitForFunction(() => document.body.innerText.includes('Guarde estas'), { timeout: 20000 })
await page.click('input[type=checkbox]'); await click('Continuar'); await page.waitForSelector('input[id^=palavra-]'); await click('Fazer depois')
await page.waitForFunction(() => document.body.innerText.includes('Olá'))
await click('Ajustes'); await page.waitForSelector('.key'); await new Promise((r) => setTimeout(r, 2500))
await click('Enviar comentário'); await page.waitForSelector('#texto')
await page.type('#texto', 'Teste de comentário: o botão de enviar ficou meio escondido.')
await click('Enviar')
await page.waitForFunction(() => location.pathname.includes('/conversa/'), { timeout: 15000 })
await page.waitForFunction(() => [...document.querySelectorAll('.status')].some((s) => s.textContent.includes('✓')), { timeout: 15000 })
const t = await text()
ok(t.includes('Lero-lero (comentários)') && t.includes('[Bug] Teste de comentário'), 'comentário enviado, aparece na conversa "Lero-lero (comentários)" com ✓')
await browser.close()
