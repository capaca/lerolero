import puppeteer from 'puppeteer-core'
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', defaultViewport: { width: 400, height: 900 } })
const ctx = browser.defaultBrowserContext()
await ctx.overridePermissions('http://localhost:4180', ['clipboard-read', 'clipboard-write', 'clipboard-sanitized-write'])
const page = await browser.newPage()
page.on('pageerror', (e) => console.log('ERRO:', String(e)))
const click = (label) => page.evaluate((l) => [...document.querySelectorAll('a,button')].find((e) => e.textContent.trim().startsWith(l)).click(), label)
await page.goto('http://localhost:4180/lerolero/')
await page.waitForFunction(() => location.pathname.endsWith('/bem-vindo'))
await click('Criar minha conta'); await page.waitForSelector('#nome'); await page.type('#nome', 'Ana'); await click('Continuar')
await page.waitForSelector('#pin'); await page.type('#pin', '135790'); await page.type('#pin2', '135790'); await click('Criar conta')
await page.waitForFunction(() => document.body.innerText.includes('Guarde estas 12 palavras'), { timeout: 20000 })
const words = await page.$$eval('ol li', (lis) => lis.map((li) => li.textContent.replace(/^\d+/, '').trim()).join(' '))
await click('Copiar a frase'); await new Promise((r) => setTimeout(r, 300))
const clip = await page.evaluate(() => navigator.clipboard.readText())
console.log(clip === words ? '✓ copiou as 12 palavras, separadas por espaço' : `✗ copiou: "${clip}"`)
console.log('botão:', await page.evaluate(() => [...document.querySelectorAll('button')].find((b) => b.textContent.includes('Copiad'))?.textContent))
await page.screenshot({ path: process.env.S + '/frase.png', fullPage: true })
await browser.close()
