import puppeteer from 'puppeteer-core'
const URL0 = 'http://localhost:4180/lerolero/'
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', defaultViewport: { width: 400, height: 850 } })
const step = (s) => console.log('✓', s)
const wait = (ms) => new Promise((r) => setTimeout(r, ms))

async function fresh() {
  const ctx = await browser.createBrowserContext()
  const page = await ctx.newPage()
  page.on('pageerror', (e) => console.log('ERRO NA PÁGINA:', String(e)))
  page.on('console', (m) => m.type() === 'error' && !m.text().includes('404') && console.log('console:', m.text()))
  await page.goto(URL0)
  return { ctx, page }
}
const text = (page) => page.evaluate(() => document.body.innerText)
const path = (page) => page.evaluate(() => location.pathname)
async function clickText(page, label) {
  const ok = await page.evaluate((label) => {
    const el = [...document.querySelectorAll('a,button')].find((e) => e.textContent.trim().startsWith(label))
    if (el) el.click()
    return !!el
  }, label)
  if (!ok) throw new Error('não achei: ' + label)
}
async function type(page, sel, value) { await page.$eval(sel, (e) => { e.value = '' }); await page.type(sel, value) }

